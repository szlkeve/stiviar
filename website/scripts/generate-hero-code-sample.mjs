// Run with: node scripts/generate-hero-code-sample.mjs
// Regenerate any time you change the sample code below.
import { codeToHtml } from "shiki";
import { rendererRich, transformerTwoslash } from "@shikijs/twoslash";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);

// Bundle the twoslash popup CSS directly into the output, so the component
// doesn't depend on a separate global CSS import that Docusaurus may or may
// not resolve correctly.
const twoslashCss = readFileSync(
  require.resolve("@shikijs/twoslash/style-rich.css"),
  "utf8",
);

const codeHtml = await codeToHtml(`console.log('hello world')`, {
  lang: "ts",
  theme: "vitesse-dark",
  transformers: [
    transformerTwoslash({
      renderer: rendererRich({ jsdoc: false }), // drop the MDN blurb, keep just the type signature
    }),
  ],
});

const html = `<style>${twoslashCss}</style>${codeHtml}`;

writeFileSync(
  new URL("../src/components/heroCodeSample.generated.ts", import.meta.url),
  `// Auto-generated by scripts/generate-hero-code-sample.mjs — do not edit by hand.\nexport const heroCodeSampleHtml = ${JSON.stringify(html)};\n`,
);
